def test_structures_preserve_equal_btc_quantity_and_balance_identity() -> None:
    policy = FinancingPolicy()
    structures = structure_scenarios(policy, reference_price=80_000.0)

    for structure in structures.values():
        assert structure.spot_qty == pytest.approx(structure.perp_qty)
        assert structure.quantity_delta == pytest.approx(0.0)
        balance = structure.balance_sheet()
        assert balance["identity_residual"] == pytest.approx(0.0)
        assert balance["net_equity"] == pytest.approx(policy.equity)


