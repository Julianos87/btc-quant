def test_fully_loaded_break_even_includes_round_trip_costs_and_target_return() -> None:
    policy = FinancingPolicy()
    structure = structure_scenarios(policy, reference_price=80_000.0)["A_CURRENT_V1_3X"]
    assert structure.round_trip_cost(policy) == pytest.approx(48.0)
    target_zero = structure.fully_loaded_break_even(policy, 90, return_capital_base=policy.equity)
    target_three = structure.fully_loaded_break_even(
        policy, 90, target_return_on_equity=0.03, return_capital_base=policy.equity
    )
    assert target_three > target_zero > structure.recurring_break_even


