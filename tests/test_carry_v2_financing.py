def test_artifact_provenance_and_governance_are_fail_closed() -> None:
    artifact_path = Path("audit/carry_v2_financing_feasibility.json")
    if not artifact_path.exists():
        pytest.skip("artifact is generated by commit B")
    root = Path(__file__).resolve().parents[1]
    require_git_worktree(root)
    artifact_name = "audit/carry_v2_financing_feasibility.json"
    artifact = json.loads(artifact_path.read_text(encoding="utf-8"))
    source_sha = artifact["qualification_source_sha"]
    assert len(source_sha) == 40
    source_available = (
        subprocess.run(
            ["git", "-C", str(root), "cat-file", "-e", f"{source_sha}^{{commit}}"],
            check=False,
        ).returncode
        == 0
    )
    if not source_available:
        shallow = subprocess.check_output(
            ["git", "-C", str(root), "rev-parse", "--is-shallow-repository"], text=True
        ).strip()
        if shallow == "true":
            pytest.skip("source commit unavailable in shallow CI checkout")
        raise AssertionError("qualification source SHA is not available in full clone")
    assert (
        subprocess.check_output(
            ["git", "-C", str(root), "rev-parse", f"{source_sha}^{{commit}}"], text=True
        ).strip()
        == source_sha
    )
    assert (
        artifact["qualification_source_tree"]
        == subprocess.check_output(
            ["git", "-C", str(root), "rev-parse", f"{source_sha}^{{tree}}"], text=True
        ).strip()
    )
    artifact_commit = subprocess.check_output(
        ["git", "-C", str(root), "log", "--all", "--format=%H", "-1", "--", artifact_name],
        text=True,
    ).strip()
    assert artifact_commit != source_sha
    assert (
        subprocess.check_output(
            ["git", "-C", str(root), "rev-parse", f"{artifact_commit}^"], text=True
        ).strip()
        == source_sha
    )
    assert subprocess.check_output(
        ["git", "-C", str(root), "diff", "--name-only", f"{artifact_commit}^", artifact_commit],
        text=True,
    ).splitlines() == ["audit/carry_v2_financing_feasibility.json"]
    assert artifact["financing"]["liquidation"]["qualification"] is False
    assert artifact["account_specific"]["portfolio_margin_eligibility"] == "UNKNOWN"
    assert artifact["governance"] == {
        "adopted": False,
        "candidate_search": {"performed": False},
        "governed_selection_permitted": False,
        "policy_changed": False,
        "threshold_search": {"performed": False},
    }


