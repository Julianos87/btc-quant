def test_structure_borrow_rate_is_authoritative_over_policy_default() -> None:
    policy = FinancingPolicy(borrow_rate_ann=0.10)
    structure = structure_scenarios(policy, reference_price=80_000.0)["A_CURRENT_V1_3X"]
    custom = type(structure)(**{**structure.__dict__, "borrow_rate_ann": 0.20})
    assert custom.annual_borrow_cost(policy) == pytest.approx(1600.0)
    assert custom.recurring_break_even == pytest.approx(8000.0 * 0.20 / 12000.0)
    edge = entry_edge(custom, smooth_funding_ann=0.10, policy=policy, return_capital_base=4000.0)
    assert edge["annual_borrow_cost"] == pytest.approx(1600.0)
    assert edge["borrow_drag_on_equity"] == pytest.approx(0.40)


